def make_icon(name: str, color: str = "#334155", size: int = 18) -> QIcon:
    """Render a crisp HiDPI SVG icon in the requested stroke color."""
    body = _SVGS.get(name, _SVGS["pages"])
    svg_xml = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'width="{size}" height="{size}" fill="none" stroke="{color}" '
        f'stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    icon = QIcon()
    for scale in (1, 2):
        px = size * scale
        pm = QPixmap(QSize(px, px))
        pm.fill(Qt.transparent)
        p = QPainter(pm)
        renderer.render(p, QRectF(0, 0, px, px))
        p.end()
        pm.setDevicePixelRatio(float(scale))
        icon.addPixmap(pm)
    return icon
